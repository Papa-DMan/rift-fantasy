"""Fantasy-side models for the LoL Worlds fantasy app (SQLAlchemy 2.0).

The `player` and `round` tables come from the lolesports models in ../db.py.
Targets PostgreSQL (BIGINT identity keys, native ENUM types, JSONB,
timestamptz). Also runs on SQLite for local tests.

Core idea: separate *ownership* (which fantasy team holds a player in a league)
from *lineups* (who that team started in a given round). Drafts and trades
only ever change ownership; scoring only ever reads lineups.
"""
from __future__ import annotations

import enum
from datetime import datetime
from typing import Any, Optional

from sqlalchemy import (
    JSON, BigInteger, CheckConstraint, DateTime, Enum, ForeignKey, Identity, Index,
    Integer, String, UniqueConstraint, func,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship


from app.db import Base  # shares MetaData with the lolesports models in ../db.py


# Reusable column helpers
# BIGINT GENERATED BY DEFAULT AS IDENTITY on Postgres. SQLite only
# auto-increments INTEGER PRIMARY KEY, so tests get Integer there.
BigIntPK = BigInteger().with_variant(Integer, "sqlite")
# JSONB on Postgres (indexable, compact); plain JSON elsewhere.
JSONType = JSON().with_variant(JSONB(), "postgresql")


def pk() -> Mapped[int]:
    return mapped_column(BigIntPK, Identity(), primary_key=True)


def created_at() -> Mapped[datetime]:
    return mapped_column(DateTime(timezone=True), server_default=func.now())


# ---------------------------------------------------------------- enums

class Slot(enum.Enum):
    TOP = "top"
    JUNGLE = "jungle"
    MID = "mid"
    ADC = "adc"
    SUPPORT = "support"
    COACH = "coach"
    BENCH = "bench"          # drop if you never want a bench


class LeagueStatus(enum.Enum):
    SETUP = "setup"          # inviting friends, editing settings
    DRAFTING = "drafting"
    ACTIVE = "active"
    FINISHED = "finished"


class DraftType(enum.Enum):
    SNAKE = "snake"
    LINEAR = "linear"


class DraftStatus(enum.Enum):
    SCHEDULED = "scheduled"
    IN_PROGRESS = "in_progress"
    COMPLETE = "complete"


class TradeStatus(enum.Enum):
    PROPOSED = "proposed"
    ACCEPTED = "accepted"    # accepted but not yet processed (veto window, etc.)
    REJECTED = "rejected"
    CANCELLED = "cancelled"
    VETOED = "vetoed"
    COMPLETED = "completed"  # ownership actually swapped


class AcquisitionType(enum.Enum):
    DRAFT = "draft"
    TRADE = "trade"
    FREE_AGENT = "free_agent"


# ---------------------------------------------------------------- users

class User(Base):
    __tablename__ = "users"

    id: Mapped[int] = pk()
    # Store lowercased; 254 is the practical max email length.
    email: Mapped[str] = mapped_column(String(254), unique=True)
    display_name: Mapped[str] = mapped_column(String(64))
    # argon2/bcrypt hashes are ASCII strings that embed salt + params.
    # Nullable so you can add OAuth (Discord/Google) logins later.
    pw_hash: Mapped[Optional[str]] = mapped_column(String(255))
    created_at: Mapped[datetime] = created_at()

    teams: Mapped[list[Team]] = relationship(back_populates="user")


# ---------------------------------------------------------------- leagues

class League(Base):
    __tablename__ = "leagues"

    id: Mapped[int] = pk()
    name: Mapped[str] = mapped_column(String(100))
    # Which competition this league follows, e.g. the Worlds 2026 tournament id
    # from lolesports. Keeps the door open for MSI / regional leagues later.
    tournament_id: Mapped[str] = mapped_column(String(64))
    # Friends-only: join by link/code instead of public discovery.
    invite_code: Mapped[str] = mapped_column(String(16), unique=True)
    max_teams: Mapped[int] = mapped_column(Integer, default=8)
    status: Mapped[LeagueStatus] = mapped_column(
        Enum(LeagueStatus), default=LeagueStatus.SETUP
    )
    # Scoring is TBD, so keep rules as data rather than columns:
    # {"kill": 3, "death": -1, "assist": 2, "cs_per_100": 1, ...}
    scoring_rules: Mapped[dict[str, Any]] = mapped_column(JSONType, default=dict)
    # e.g. {"top": 1, "jungle": 1, "mid": 1, "adc": 1, "support": 1,
    #       "coach": 1, "bench": 2}
    roster_slots: Mapped[dict[str, int]] = mapped_column(JSONType, default=dict)
    trade_deadline: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    created_by_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    created_at: Mapped[datetime] = created_at()

    teams: Mapped[list[Team]] = relationship(back_populates="league")
    draft: Mapped[Optional[Draft]] = relationship(back_populates="league")


class Team(Base):
    """A user's membership in a league *is* their fantasy team (was league_membership)."""
    __tablename__ = "teams"
    __table_args__ = (
        UniqueConstraint("league_id", "user_id"),   # one team per user per league
        UniqueConstraint("league_id", "name"),
    )

    id: Mapped[int] = pk()
    league_id: Mapped[int] = mapped_column(ForeignKey("leagues.id", ondelete="CASCADE"))
    user_id: Mapped[int] = mapped_column(ForeignKey("users.id"))
    name: Mapped[str] = mapped_column(String(64))
    is_commissioner: Mapped[bool] = mapped_column(default=False)
    joined_at: Mapped[datetime] = created_at()

    league: Mapped[League] = relationship(back_populates="teams")
    user: Mapped[User] = relationship(back_populates="teams")
    players: Mapped[list[TeamPlayer]] = relationship(back_populates="team")


class TeamPlayer(Base):
    """Ownership: which team currently holds which pro player in a league.

    The (league_id, player_id) unique constraint is what stops two friends
    from owning Faker at the same time. league_id is denormalised from the
    team purely so the database can enforce that.
    """
    __tablename__ = "team_players"
    __table_args__ = (UniqueConstraint("league_id", "player_id"),)

    id: Mapped[int] = pk()
    league_id: Mapped[int] = mapped_column(ForeignKey("leagues.id", ondelete="CASCADE"))
    team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"), index=True)
    player_id: Mapped[int] = mapped_column(ForeignKey("player.id"))
    acquired_via: Mapped[AcquisitionType] = mapped_column(Enum(AcquisitionType))
    acquired_at: Mapped[datetime] = created_at()

    team: Mapped[Team] = relationship(back_populates="players")


# ---------------------------------------------------------------- lineups

class LineupSlot(Base):
    """Who a team started in a given round. One row per filled slot.

    Rows are written when the round locks (or edited until then), so past
    rounds keep their history even after trades.
    """
    __tablename__ = "lineup_slots"
    __table_args__ = (
        UniqueConstraint("team_id", "round_id", "slot", "slot_index"),
        UniqueConstraint("team_id", "round_id", "player_id"),  # no player twice
    )

    id: Mapped[int] = pk()
    team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"))
    round_id: Mapped[int] = mapped_column(ForeignKey("round.id"))
    slot: Mapped[Slot] = mapped_column(Enum(Slot))
    slot_index: Mapped[int] = mapped_column(Integer, default=0)  # for BENCH 0..n
    player_id: Mapped[int] = mapped_column(ForeignKey("player.id"))
    # Cached once the round is final; recompute if scoring_rules change.
    points: Mapped[Optional[float]] = mapped_column()


# ---------------------------------------------------------------- draft

class Draft(Base):
    __tablename__ = "drafts"

    id: Mapped[int] = pk()
    league_id: Mapped[int] = mapped_column(
        ForeignKey("leagues.id", ondelete="CASCADE"), unique=True
    )
    type: Mapped[DraftType] = mapped_column(Enum(DraftType), default=DraftType.SNAKE)
    status: Mapped[DraftStatus] = mapped_column(Enum(DraftStatus), default=DraftStatus.SCHEDULED)
    scheduled_for: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    seconds_per_pick: Mapped[int] = mapped_column(Integer, default=90)
    started_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))

    league: Mapped[League] = relationship(back_populates="draft")
    picks: Mapped[list[DraftPick]] = relationship(
        back_populates="draft", order_by="DraftPick.overall_pick"
    )


class DraftPick(Base):
    """Generate every pick row (with team_id, player_id NULL) when the draft
    starts. The draft order and 'whose turn is it' then fall out of the
    first row with player_id IS NULL, and snake vs linear is decided once."""
    __tablename__ = "draft_picks"
    __table_args__ = (
        UniqueConstraint("draft_id", "overall_pick"),
        UniqueConstraint("draft_id", "player_id"),  # NULLs don't collide
    )

    id: Mapped[int] = pk()
    draft_id: Mapped[int] = mapped_column(ForeignKey("drafts.id", ondelete="CASCADE"))
    overall_pick: Mapped[int] = mapped_column(Integer)
    round_number: Mapped[int] = mapped_column(Integer)
    team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"))
    player_id: Mapped[Optional[int]] = mapped_column(ForeignKey("player.id"))
    is_autopick: Mapped[bool] = mapped_column(default=False)
    picked_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))

    draft: Mapped[Draft] = relationship(back_populates="picks")


# ---------------------------------------------------------------- trades

class Trade(Base):
    __tablename__ = "trades"
    __table_args__ = (
        CheckConstraint("proposer_team_id <> receiver_team_id"),
        Index("ix_trades_league_status", "league_id", "status"),
    )

    id: Mapped[int] = pk()
    league_id: Mapped[int] = mapped_column(ForeignKey("leagues.id", ondelete="CASCADE"))
    proposer_team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"))
    receiver_team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"))
    status: Mapped[TradeStatus] = mapped_column(Enum(TradeStatus), default=TradeStatus.PROPOSED)
    message: Mapped[Optional[str]] = mapped_column(String(500))
    created_at: Mapped[datetime] = created_at()
    responded_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True))

    items: Mapped[list[TradeItem]] = relationship(back_populates="trade")


class TradeItem(Base):
    """One player moving in a trade. Supports 1-for-1, 2-for-1, etc.
    from_team_id says which side gives the player; the other side receives."""
    __tablename__ = "trade_items"
    __table_args__ = (UniqueConstraint("trade_id", "player_id"),)

    id: Mapped[int] = pk()
    trade_id: Mapped[int] = mapped_column(ForeignKey("trades.id", ondelete="CASCADE"))
    from_team_id: Mapped[int] = mapped_column(ForeignKey("teams.id", ondelete="CASCADE"))
    player_id: Mapped[int] = mapped_column(ForeignKey("player.id"))

    trade: Mapped[Trade] = relationship(back_populates="items")
